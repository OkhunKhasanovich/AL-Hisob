/// Роль пользователя в приложении. Один аккаунт может совмещать роли,
/// поэтому в БД роли хранятся набором, хотя при онбординге выбирается одна.
enum ShopRole {
  /// Оптовик (ulgurji savdo).
  wholesaler,

  /// Розничный продавец: магазин, торговая точка (в интерфейсе — «Розничный продавец» / «Chakana savdo»).
  /// Техническое имя `buyer` оставлено прежним: оно хранится в БД и уходит на сервер,
  /// переименование сломало бы данные старых версий приложения.
  buyer,

  /// Грузчик (этап 7).
  loader,

  /// Доставщик (этап 7).
  courier,
}
