/// Чья задолженность в записи книги.
///
/// Техническое значение хранится числом (0/1) в БД и уходит на сервер: порядок менять нельзя.
enum DebtDirection {
  /// Мне должны (покупатели, клиенты) — основная книга должников.
  receivable,

  /// Я должен (поставщики, оптовики) — «Мои долги поставщикам».
  payable,
}
