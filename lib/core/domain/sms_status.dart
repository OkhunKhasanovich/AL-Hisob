/// Итог попытки отправить SMS.
enum SmsStatus {
  /// Телефон принял сообщение к отправке (Android: сеть подтвердила отправку).
  sent,

  /// Отправка не удалась (нет сети, нет разрешения, ошибка модема...).
  failed,

  /// Открыто системное окно SMS; отправил ли пользователь — неизвестно (iOS).
  composerOpened,
}
